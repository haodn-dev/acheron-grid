/** English keys are also override keys; column titles, data and host labels are never implicitly translated. */
export function createCanvasTranslator(
  locale = 'en',
  messages: Readonly<Record<string, string>> = {},
): CanvasTranslator {
  if (
    typeof locale !== 'string' ||
    !locale ||
    !messages ||
    typeof messages !== 'object' ||
    Array.isArray(messages) ||
    Object.values(messages).some((value) => typeof value !== 'string')
  )
    throw new TypeError('Invalid Canvas localization.');
  const dictionary = Object.freeze({
    ...(locale.toLowerCase().startsWith('vi') ? canvasVietnameseMessages : {}),
    ...messages,
  });
  const patterns = Object.keys(dictionary)
    .filter((key) => /\{\d+\}/.test(key))
    .map((key) => {
      const parts = key.split(/\{\d+\}/g).map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'));
      return { key, pattern: new RegExp('^' + parts.join('(.*?)') + '$') };
    });
  return (message, ...values) => {
    if (!values.length && !Object.hasOwn(dictionary, message))
      for (const entry of patterns) {
        const match = entry.pattern.exec(message);
        if (match)
          return dictionary[entry.key]!.replace(/\{(\d+)\}/g, (_, index: string) => match[Number(index) + 1] ?? '');
      }
    const template = Object.hasOwn(dictionary, message) ? dictionary[message]! : message;
    return template.replace(/\{(\d+)\}/g, (token, index: string) =>
      Number(index) < values.length ? String(values[Number(index)]) : token,
    );
  };
}

